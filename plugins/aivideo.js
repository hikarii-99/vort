const axios = require('axios');

const API_KEY = 'freeApikey';

module.exports = {
    command: ['txt2vid', 'textvideo', 'aivideo', 'ttv'],
    description: 'Generate AI Video from text prompt',

    handler: async ({ socket, msg, sender, args, prefix }) => {
        try {
            const prompt = args.join(' ').trim();

            if (!prompt) {
                return await socket.sendMessage(sender, {
                    text: `🎬 *VORTEX MD | AI Video Generator*\n\n` +
                        `*Usage:* ${prefix}tv <prompt>\n\n` +
                        `*Examples:*\n` +
                        `${prefix}tv a dragon flying over mountains\n` +
                        `${prefix}tv vibrant surreal landscape\n` +
                        `${prefix}tv ocean waves at sunset\n\n` +
                        `⏱️ _Generation takes ~2 minutes_\n\n` +
                        `> *Powered by VORTEX MD*`
                }, { quoted: msg });
            }

            await socket.sendMessage(sender, { react: { text: '⏳', key: msg.key } });
            await socket.sendMessage(sender, {
                text: `🎬 *Generating AI Video...*\n\n` +
                    `📝 *Prompt:* ${prompt}\n\n` +
                    `_This takes about 2 minutes, please wait..._`
            }, { quoted: msg });

            const { data } = await axios.get(
                `https://anabot.my.id/api/ai/text2video?prompt=${encodeURIComponent(prompt)}&apikey=${encodeURIComponent(API_KEY)}`,
                { timeout: 180000 }
            );

            if (!data.success || !data.data?.result) {
                return await socket.sendMessage(sender, {
                    text: `❌ *Video generation failed!* Try again.`
                }, { quoted: msg });
            }

            const videoUrl = data.data.result;

            const caption = `🎬 *VORTEX MD | AI Video*\n\n` +
                `📝 *Prompt:* ${prompt}\n\n` +
                `> *Generated by VORTEX MD AI*`;

            await socket.sendMessage(sender, {
                video: { url: videoUrl },
                mimetype: 'video/mp4',
                caption: caption
            }, { quoted: msg });

            await socket.sendMessage(sender, { react: { text: '✅', key: msg.key } });

        } catch (err) {
            console.error('Text2Video plugin error:', err.message);
            await socket.sendMessage(sender, { react: { text: '❌', key: msg.key } });
            await socket.sendMessage(sender, {
                text: `❌ *Error:* ${err.message}`
            }, { quoted: msg });
        }
    }
};
